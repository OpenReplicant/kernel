"""Memory extractor worker (M6-T4): the memories each recorded message holds, quoting it. Needs no runner.

A pass takes, per conversation, the oldest message (as:Note with as:context, from the interaction
encoder) it has not read yet, once its own earlier change sets are decided, so a message sees the memories
of the ones before it. For each, it asks a model (any OpenAI-compatible endpoint) with the message before it and
the earlier memories in its scope (the conversation's latest, then what recall finds for it), and submits one change set: the memories
(extract.ops), superseding the earlier ones they replace, generated by its own run. The quote verifier
then checks every quote against the transcript. It wakes on applied change sets and sweeps every
KK_SWEEP_SECONDS. A message the model could not be asked about is tried again on the next pass.

Runs inside `kk serve` (part `extract`, opt-in), or alone: python -m memory_extractor.
Env: DATABASE_URL (a login that may SET ROLE to KK_ROLE), KK_ROLE (default kkm_memory_extractor),
KK_EXTRACT_MODEL (default liquid/lfm-2.5-2.6b:free), KK_EXTRACT_URL (default https://openrouter.ai/api/v1),
KK_EXTRACT_KEY (or OPENROUTER_API_KEY), KK_EXTRACT_BATCH (messages per pass, default 20),
KK_SWEEP_SECONDS (default 30).
"""
import hashlib
import json
import os
import sys
import time
import urllib.error
import urllib.request

import psycopg

from kk.lib import connect, listen, run
from kk.lib import submit as kernel_submit

from .extract import AS, DCT, KIND, LABEL, RDF_TYPE, memories, ops, parse, prompt, slug

AGENT = "urn:kk:agent:memory-extractor"
METHOD = "urn:kk:module:memory-extractor"
EARLIER_MAX = 8   # earlier memories shown to the model
# Per conversation, the oldest message not read yet: the content of a note in it that is not a memory.
PENDING = f"""select id, subject, text, scope from (
  select distinct on (x.object_entity) c.id::text, c.subject, c.object_value->>'@value' as text, c.scope,
         c.recorded_at, coalesce(p.object_value->>'@value', '') as published
    from api.claims c
    join api.claims x on x.subject = c.subject and x.predicate = '{AS}context' and x.status <> 'deprecated'
    left join api.claims p on p.subject = c.subject and p.predicate = '{AS}published' and p.status <> 'deprecated'
   where c.predicate = '{AS}content' and c.status <> 'deprecated'
     and not exists (select 1 from api.claims k where k.subject = c.subject and k.status <> 'deprecated'
                     and k.predicate in ('{DCT}type', '{DCT}isPartOf'))
     and not exists (select 1 from memory_extractor.seen s where s.claim_id = c.id)
   order by x.object_entity, published, c.recorded_at, c.subject) m
 order by recorded_at limit %s"""
WAITING = "select exists (select 1 from api.change_sets where attributed_to = %s and status = 'submitted')"
# The conversation's latest memories, newest first.
RECENT = f"""select coalesce(array_agg(subject order by at desc), '{{}}') from (
  select x.subject, max(x.recorded_at) at from api.claims x
   where x.predicate = '{AS}context' and x.object_entity = %s and x.status <> 'deprecated'
     and exists (select 1 from api.claims t where t.subject = x.subject and t.predicate = '{DCT}type'
                 and starts_with(t.object_entity, '{KIND}') and t.status <> 'deprecated')
   group by x.subject order by at desc limit {EARLIER_MAX}) r"""
PART = """select object_entity, object_value->>'@value' from api.claims
           where subject = %s and predicate = %s and status <> 'deprecated' limit 1"""
LABELLED = f"""select coalesce(array_agg(distinct subject), '{{}}') from api.claims
                where subject = any(%s) and predicate = '{LABEL}' and status <> 'deprecated'"""
# Earlier memories in the scope among what recall finds for the message: their claims, by note.
EARLIER = f"""select n.subject, c.id::text, c.predicate, c.status, c.object_value->>'@value'
  from unnest(%(subjects)s::text[]) with ordinality as n(subject, rank)
  join api.claims c on c.subject = n.subject and c.status <> 'deprecated' and c.scope = %(scope)s
 where exists (select 1 from api.claims t where t.subject = n.subject and t.predicate = '{DCT}type'
               and starts_with(t.object_entity, '{KIND}') and t.status <> 'deprecated')
   and not exists (select 1 from api.claims p where p.subject = n.subject and p.predicate = '{DCT}isPartOf'
                   and p.object_entity = %(message)s)
 order by n.rank, c.predicate"""


def ask(text: str) -> tuple[str, str]:
    """One completion: (text, the model that answered). Raises when the endpoint cannot answer."""
    url = os.environ.get("KK_EXTRACT_URL", "https://openrouter.ai/api/v1").rstrip("/") + "/chat/completions"
    key = os.environ.get("KK_EXTRACT_KEY") or os.environ.get("OPENROUTER_API_KEY") or ""
    body = json.dumps({"model": model(), "temperature": 0, "max_tokens": 8000,
                       "messages": [{"role": "user", "content": text}]}).encode()
    for attempt in range(4):
        req = urllib.request.Request(url, body, {"Content-Type": "application/json", "Authorization": f"Bearer {key}"})
        try:
            with urllib.request.urlopen(req, timeout=300) as r:
                out = json.load(r)
            if out.get("choices"):
                return out["choices"][0]["message"]["content"] or "", out.get("model") or model()
        except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError) as e:
            if getattr(e, "code", 429) not in (429, 500, 502, 503):
                raise
        time.sleep(2 ** attempt * 5)
    raise RuntimeError("the model endpoint did not answer")


def model() -> str:
    return os.environ.get("KK_EXTRACT_MODEL", "liquid/lfm-2.5-2.6b:free")


def part(cur, subject: str | None, predicate: str) -> tuple[str | None, str | None]:
    if not subject:
        return None, None
    cur.execute(PART, (subject, predicate))
    return cur.fetchone() or (None, None)


def label(cur, iri: str | None) -> str:
    return (part(cur, iri, LABEL)[1] or (iri or "").rsplit(":", 1)[-1]) if iri else ""


def earlier(cur, text: str, scope: str, message: str, context: str | None) -> list[tuple[str, dict]]:
    """(sentence with its date, its claims) for the earlier memories: the conversation's latest, then
    what recall finds for the message."""
    hits = []
    if context:
        cur.execute(RECENT, (context,))
        hits += cur.fetchone()[0]
    cur.execute("select to_regprocedure('api.recall(text,integer)') is not null")
    if cur.fetchone()[0]:
        cur.execute("select api.recall(%s, 40)", (text[:2000],))
        hits += [h["subject"] for h in (cur.fetchone()[0] or [])]
    if not hits:
        return []
    cur.execute(EARLIER, {"subjects": list(dict.fromkeys(hits)), "scope": scope, "message": message})
    notes: dict[str, dict] = {}
    for subject, cid, predicate, status, value in cur.fetchall():
        n = notes.setdefault(subject, {"claims": []})
        n["claims"].append({"id": cid, "predicate": predicate, "status": status})
        if predicate == AS + "content":
            n["text"] = value
        elif predicate == AS + "published":
            n["when"] = (value or "")[:10]
    return [((f"({n['when']}) " if n.get("when") else "") + n["text"], n)
            for n in list(notes.values()) if n.get("text")][:EARLIER_MAX]


def extract(cur, claim_id: str, subject: str, text: str, scope: str) -> dict | None:
    """The change set for one message (None when it holds nothing), and how many memories it gives."""
    author = part(cur, subject, AS + "attributedTo")[0]
    published = part(cur, subject, AS + "published")[1]
    context = part(cur, subject, AS + "context")[0]
    before = part(cur, subject, AS + "inReplyTo")[0]
    previous = part(cur, before, AS + "content")[1] if before else None
    previous_author = label(cur, part(cur, before, AS + "attributedTo")[0]) if before else ""
    prior = earlier(cur, text, scope, subject, context)
    answer, used = ask(prompt(text, label(cur, author), published or "", previous or "", previous_author,
                              [s for s, _ in prior]))
    cur.execute("select exists (select 1 from api.claims where subject = %s and predicate = %s"
                " and object_entity = %s and status <> 'deprecated')", (author, RDF_TYPE, AS + "Application"))
    found = memories(parse(answer), text, len(prior), agent=cur.fetchone()[0])
    cur.execute("select api.explain(%s::uuid)->'references'->0->>'artifact'", (claim_id,))
    artifact = cur.fetchone()[0]
    topics = sorted({f"urn:kk:topic:{slug(m['about'])}" for m in found if m["about"]})
    cur.execute(LABELLED, (topics,))
    named = set(cur.fetchone()[0])
    message = {"subject": subject, "author": author or AGENT, "context": context, "published": published}
    body = ops(found, message, artifact, {i: n["claims"] for i, (_, n) in enumerate(prior, 1)}, named)
    digest = hashlib.sha256(json.dumps([claim_id, body], sort_keys=True).encode()).hexdigest()[:32]
    return {"model": used, "memories": len(found),
            "change_set": {"idempotency_key": f"extract:{digest}", "attributed_to": AGENT, "target_scope": scope,
                           "ops": body} if body else None}


def step(conn) -> None:
    batch = int(os.environ.get("KK_EXTRACT_BATCH", "20"))
    with conn.cursor() as cur:
        cur.execute(WAITING, (AGENT,))
        if cur.fetchone()[0]:   # the validator has not decided our last memories: the next pass
            return
        cur.execute(PENDING, (batch,))
        for claim_id, subject, text, scope in cur.fetchall():
            try:
                with run(cur, METHOD, used=[claim_id]) as (run_id, outputs):
                    got = extract(cur, claim_id, subject, text or "", scope)
                    outputs.update(memories=got["memories"], model=got["model"])
                    status = kernel_submit(cur, got["change_set"], run_id)["status"] if got["change_set"] else "none"
                cur.execute("insert into memory_extractor.seen(claim_id, memories, model) values (%s, %s, %s)"
                            " on conflict do nothing", (claim_id, got["memories"], got["model"]))
                print(f"extract: {subject}: {got['memories']} memories -> {status}", flush=True)
            except (OSError, RuntimeError, urllib.error.HTTPError) as e:   # the model: try again next pass
                print(f"extract: {subject}: the model did not answer ({str(e)[:120]}); later", flush=True)
                return
            except psycopg.Error as e:   # one bad message must not stop the others
                print(f"extract: {subject}: {e.diag.message_primary or e}", flush=True)
                cur.execute("insert into memory_extractor.seen(claim_id, memories, model) values (%s, 0, %s)"
                            " on conflict do nothing", (claim_id, "error: " + str(e.diag.sqlstate)))


def main() -> None:
    with connect(os.environ.get("KK_ROLE", "kkm_memory_extractor")) as conn:
        print(f"extract: {model()}; listening on kernel_change_set", flush=True)
        listen(conn, step, wake=lambda p: json.loads(p).get("status") == "applied")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(0)
