"""Truth maintenance worker (D-89, M6-T12): flags claims whose premises were withdrawn. Needs no runner.

A pass follows `derived_from` from every withdrawn claim (deprecated or redacted) to the current claims
built on it, directly or through other derived claims, and compares with its own latest verdicts
(plan.verdicts). It submits one change set of add_verification ops per scope, each generated by its own
run: inconclusive when a premise is gone, supported when every premise is current again. The belief
model caps a claim whose latest verdict here is inconclusive. It wakes on applied change sets and sweeps
every KK_SWEEP_SECONDS.

Runs inside `kk serve` (part `tms`), or alone: python -m truth_maintenance.
Env: DATABASE_URL (a login that may SET ROLE to KK_ROLE), KK_ROLE (default kkm_truth_maintenance),
KK_SWEEP_SECONDS (default 30).
"""
import hashlib
import json
import os
import sys

import psycopg

from kk.lib import connect, listen, run
from kk.lib import submit as kernel_submit

from .plan import METHOD, verdicts

AGENT = "urn:kk:agent:truth-maintenance"
# Current claims built on a withdrawn claim, with the withdrawn claims behind each. `fallen` starts from the
# withdrawn claims that something was derived from and follows derivations down; a claim that is itself
# withdrawn is history, not flagged.
UNDERMINED = """
with recursive fallen(id, root) as (
  select c.id, c.id from api.claims c
   where (c.status = 'deprecated' or c.redacted_at is not null)
     and exists (select 1 from kernel.claim_derivation d where d.derived_from = c.id)
  union
  select d.claim_id, f.root from kernel.claim_derivation d join fallen f on d.derived_from = f.id
)
select f.id::text, c.scope, array_agg(distinct f.root::text) from fallen f join api.claims c on c.id = f.id
 where f.id <> f.root and c.status <> 'deprecated' and c.redacted_at is null
 group by f.id, c.scope"""
# This method's latest verdict on each claim it has judged that is still current.
LATEST = """select distinct on (v.claim_id) v.claim_id::text, c.scope, v.verdict, v.recorded_at::text
            from api.verifications v
            join api.claims c on c.id = v.claim_id
            where v.method = %s and c.status <> 'deprecated' and c.redacted_at is null
            order by v.claim_id, v.recorded_at desc"""


def change_sets(cur) -> list[dict]:
    """The verification change sets one pass would submit."""
    cur.execute(UNDERMINED)
    undermined, scope = {}, {}
    for claim, sc, roots in cur.fetchall():
        undermined[claim], scope[claim] = roots, sc
    cur.execute(LATEST, (METHOD,))
    latest, since = {}, {}
    for claim, sc, verdict, at in cur.fetchall():
        latest[claim], scope[claim], since[claim] = verdict, sc, at
    ops_by_scope: dict[str, list] = {}
    for claim, verdict, details in verdicts(undermined, latest):
        ops_by_scope.setdefault(scope[claim], []).append(
            {"op": "add_verification", "claim": claim, "verdict": verdict, "method": METHOD, "details": details})
    out = []
    for sc, ops in sorted(ops_by_scope.items()):
        # The time of each claim's latest verdict is part of the key: flagging a claim again after it was
        # restored is a new change set, not the first one returned again.
        digest = hashlib.sha256(json.dumps([ops, [since.get(op["claim"]) for op in ops]], sort_keys=True)
                                .encode()).hexdigest()[:32]
        out.append({"idempotency_key": f"tms:{digest}", "attributed_to": AGENT,
                    "target_scope": sc, "ops": ops})
    return out


def step(conn) -> None:
    with conn.cursor() as cur:
        for cs in change_sets(cur):
            try:
                with run(cur, METHOD) as (run_id, outputs):
                    outputs["ops"] = len(cs["ops"])
                    status = kernel_submit(cur, cs, run_id)["status"]
                flagged = sum(op["verdict"] == "inconclusive" for op in cs["ops"])
                print(f"tms: {cs['target_scope']}: {flagged} flagged, {len(cs['ops']) - flagged} restored -> {status}",
                      flush=True)
            except psycopg.Error as e:  # one bad scope must not stop the others
                print(f"tms: {cs['target_scope']}: {e.diag.message_primary or e}", flush=True)


def main() -> None:
    with connect(os.environ.get("KK_ROLE", "kkm_truth_maintenance")) as conn:
        print("tms: listening on kernel_change_set", flush=True)
        listen(conn, step, wake=lambda p: json.loads(p).get("status") == "applied")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(0)
