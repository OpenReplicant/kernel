"""Quote verifier worker (M3-T6): checks that extracted claims' quotes occur in their sources. Needs no runner.

A pass takes the extracted claims this module can read that it has not verified yet, reads each quoted
reference's source (check.verdict) and submits one change set of add_verification ops per scope, each
generated by its own run. A claim whose source cannot be read here (another machine's file, an artifact
in another store) is left unverified and tried again on the next start. It wakes on applied change sets
and sweeps every KK_SWEEP_SECONDS.

Runs inside `kk serve` (part `quotes`), or alone: python -m verifier_quotes.
Env: DATABASE_URL (a login that may SET ROLE to KK_ROLE), KK_ROLE (default kkm_verifier_quotes),
KK_ARTIFACTS (default ~/.local/share/knowledge-kernel/artifacts), KK_SOURCE_ROOT (default the working
directory), KK_SWEEP_SECONDS (default 30).
"""
import hashlib
import json
import os
import sys
from pathlib import Path

import psycopg

from kk.lib import connect, listen, run
from kk.lib import submit as kernel_submit

from .check import verdict

AGENT = "urn:kk:agent:verifier-quotes"
MODULE = "urn:kk:module:verifier-quotes"
PENDING = """select c.id, c.scope from api.claims c
             where c.evidence_type = 'extracted' and c.redacted_at is null and not (c.id::text = any(%(skip)s::text[]))
               and not exists (select 1 from api.verifications v where v.claim_id = c.id and v.method = %(m)s)
             order by c.recorded_at limit 500"""


def change_sets(cur, store: Path, root: Path, skip: set) -> list[dict]:
    """The verification change sets one pass would submit; claims it cannot judge go into `skip`."""
    cur.execute(PENDING, {"skip": sorted(skip), "m": MODULE})
    claims = cur.fetchall()
    if not claims:
        return []
    cur.execute("select claim_id, artifact, source_uri, quote from api.claim_references where claim_id = any(%s)",
                ([c[0] for c in claims],))
    refs: dict = {}
    for claim_id, artifact, source_uri, quote in cur.fetchall():
        refs.setdefault(claim_id, []).append({"artifact": artifact, "source_uri": source_uri, "quote": quote})
    ops_by_scope: dict[str, list] = {}
    for claim_id, scope in claims:
        result, details = verdict(refs.get(claim_id, []), store, root)
        if result is None:
            skip.add(str(claim_id))
            continue
        ops_by_scope.setdefault(scope, []).append(
            {"op": "add_verification", "claim": str(claim_id), "verdict": result, "method": MODULE,
             "details": {"check": "quote occurs in source", **details}})
    out = []
    for scope, ops in sorted(ops_by_scope.items()):
        digest = hashlib.sha256(json.dumps(ops, sort_keys=True).encode()).hexdigest()[:24]
        out.append({"idempotency_key": f"quotes:{digest}", "attributed_to": AGENT, "target_scope": scope, "ops": ops})
    return out


class Pass:
    def __init__(self, store: Path, root: Path):
        self.store, self.root, self.skip = store, root, set()

    def __call__(self, conn) -> None:
        with conn.cursor() as cur:
            while sets := change_sets(cur, self.store, self.root, self.skip):
                for cs in sets:
                    try:
                        with run(cur, MODULE) as (run_id, outputs):
                            outputs["ops"] = len(cs["ops"])
                            status = kernel_submit(cur, cs, run_id)["status"]
                        refuted = sum(op["verdict"] == "refuted" for op in cs["ops"])
                        print(f"quotes: {cs['target_scope']}: {len(cs['ops'])} verified, {refuted} refuted -> {status}",
                              flush=True)
                        if status != "applied":   # do not retry a refused set in this pass
                            self.skip.update(op["claim"] for op in cs["ops"])
                    except psycopg.Error as e:  # one bad scope must not stop the others
                        self.skip.update(op["claim"] for op in cs["ops"])
                        print(f"quotes: {cs['target_scope']}: {e.diag.message_primary or e}", flush=True)


def main() -> None:
    store = Path(os.environ.get("KK_ARTIFACTS") or Path.home() / ".local/share/knowledge-kernel/artifacts")
    root = Path(os.environ.get("KK_SOURCE_ROOT") or os.getcwd())
    with connect(os.environ.get("KK_ROLE", "kkm_verifier_quotes")) as conn:
        if conn.execute("select to_regclass('api.verifications')").fetchone()[0] is None:
            sys.exit("verifier-quotes: not installed (its migration adds api.verifications)")
        print(f"quotes: artifacts in {store}, file: sources under {root}; listening on kernel_change_set", flush=True)
        listen(conn, Pass(store, root), wake=lambda p: json.loads(p).get("status") == "applied")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(0)
