"""Vocabulary pack loader: turns the local packs (ontology/packs.yaml entries with a `file`) and the
slot catalog (ontology/slots.yaml) into one kernel.install_ops call each, written as a SQL migration.
It also registers the identifiers of the shipped chains and steps (see chain_identifiers).

Usage:  python -m pack_loader > modules/pack-loader/packs.sql      (run from modules/pack-loader,
        or with PYTHONPATH=modules/pack-loader from the repository root)

The output is committed and reviewed as code (D-19); deploy/postgres/030_packs.sh applies it on first
database start. Typing claims (`x a owl:ObjectProperty`, ...) are what make a property approved.
Every claim references its source file, pinned by content hash.
"""
import hashlib
import json
import sys
from pathlib import Path

import rdflib
import yaml
from rdflib import BNode, Literal, URIRef

ROOT = Path(__file__).resolve().parents[3]
AGENT = "urn:kk:agent:pack-loader"
MODULE = "urn:kk:module:pack-loader"
SCOPE = "urn:kk:scope:vocab"
KK = "https://w3id.org/knowledge-kernel/ns#"


def source(rel: str) -> dict:
    digest = hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()
    return {"source_uri": f"file:{rel}#sha256={digest}"}


def obj(o) -> dict:
    if isinstance(o, URIRef):
        return {"entity": str(o)}
    if isinstance(o, Literal):
        v = {"@value": str(o)}
        if o.language:
            v["@language"] = o.language
        elif o.datatype:
            v["@type"] = str(o.datatype)
        return {"value": v}
    raise ValueError(f"blank nodes are not supported in packs: {o!r}")


def claim(s, p, o, ref: dict) -> dict:
    return {"op": "add_claim", "subject": str(s), "predicate": str(p), "object": obj(o),
            "evidence_type": "deterministic", "references": [ref]}


def pack_ops(rel: str) -> list:
    g = rdflib.Graph().parse(ROOT / rel)
    ref = source(rel)
    ops = []
    for s, p, o in sorted(g):
        if isinstance(s, BNode):
            raise ValueError(f"{rel}: blank node subject {s!r}")
        ops.append(claim(s, p, o, ref))
    return ops


def slot_ops(rel: str) -> list:
    catalog = yaml.safe_load((ROOT / rel).read_text())
    ref = source(rel)
    ops = []
    for group, slots in catalog["groups"].items():
        for slot in slots:
            s = URIRef(f"urn:kk:slot:{slot['id']}")
            ops += [
                claim(s, rdflib.RDF.type, URIRef(KK + "Slot"), ref),
                claim(s, rdflib.RDFS.label, Literal(slot["id"]), ref),
                claim(s, URIRef(KK + "slotContract"), Literal(slot["contract"]), ref),
                claim(s, URIRef(KK + "cardinality"), Literal(slot["cardinality"]), ref),
            ]
    return ops


def install(key: str, ops: list) -> str:
    body = json.dumps(ops, indent=None, ensure_ascii=False)
    if "$kk$" in body:
        raise ValueError(f"{key}: content contains the SQL quote tag $kk$")
    return (f"select kernel.install_ops('{key}', '{SCOPE}', $kk${body}$kk$::jsonb,\n"
            f"  '{AGENT}', '{MODULE}');\n")


def chain_identifiers() -> str:
    """Identifiers of every chain and step shipped in modules/*/chains, so runs can name the step
    they carry out (kernel.run.plan_step references kernel.entity). Meaning comes later, from the
    self-encoder's claims. Keyed by a hash of the IRI list: new chains or steps give a new install."""
    iris = []
    for path in sorted((ROOT / "modules").glob("*/chains/*.yaml")):
        if path.parent.parent.name.startswith("_"):
            continue
        chain = yaml.safe_load(path.read_text())
        iris.append(chain["chain"])
        iris += [f"{chain['chain']}/{step['id']}" for step in chain["steps"]]
    digest = hashlib.sha256("\n".join(iris).encode()).hexdigest()[:16]
    ops = [{"op": "add_entity", "iri": i} for i in iris]
    return (f"-- chain and step identifiers ({len(iris)})\n"
            f"select kernel.install_ops('chains:identifiers:{digest}', '{SCOPE}', $kk${json.dumps(ops)}$kk$::jsonb);\n")


def main() -> int:
    packs = yaml.safe_load((ROOT / "ontology/packs.yaml").read_text())
    out = ["-- Generated by modules/pack-loader (python -m pack_loader). Do not edit; regenerate.",
           "set role kk_owner;"]
    for tier in ("core", "profile"):
        for pack in packs.get(tier, []):
            if "file" not in pack:
                continue          # upstream vocabularies: pinned and stored as artifacts later
            rel = f"ontology/{pack['file']}"
            g = rdflib.Graph().parse(ROOT / rel)
            version = next((str(v) for v in g.objects(None, rdflib.OWL.versionInfo)), packs["version"])
            out.append(f"-- {pack['id']} ({tier}) {version}")
            out.append(install(f"pack:{pack['id']}:{version}", pack_ops(rel)))
    slots = yaml.safe_load((ROOT / "ontology/slots.yaml").read_text())
    out.append(f"-- slot catalog {slots['version']}")
    out.append(install(f"pack:slots:{slots['version']}", slot_ops("ontology/slots.yaml")))
    out.append(chain_identifiers())
    out.append("reset role;")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
