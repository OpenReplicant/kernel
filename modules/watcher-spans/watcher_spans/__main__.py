"""Span watcher (D-106): flags the claims that cite a file span which has changed. No model, needs no runner.

A pass reads every current claim whose reference pins a file span (the span's source is a file: URI, its
value a line locator, the quote the pinned text), re-reads the file under the source roots (check.judge)
and compares. It submits one change set of add_verification ops per scope, each generated by its own run:
inconclusive for a claim citing a span that moved, changed or whose file is gone (the details name the
span and, for a moved one, where the text went); supported again when every span it cites is as pinned.
The latest verdict of this method decides, so running again over an unchanged tree submits nothing. It
writes no claims and deletes nothing; a claim is replaced the usual way, by the encoder reading the file
again and superseding the old span.

Runs inside `kk serve` (part `spans`), or alone: python -m watcher_spans.
Env: DATABASE_URL (a login that may SET ROLE to KK_ROLE), KK_ROLE (default kkm_watcher_spans),
KK_SOURCE_ROOTS (directories where file: sources resolve, separated like PATH; default the working
directory; a path may point into several checkouts), KK_SWEEP_SECONDS (default 30).
"""
import hashlib
import json
import os
import sys
from pathlib import Path

import psycopg

from kk.lib import connect, listen, run
from kk.lib import submit as kernel_submit

from .check import METHOD, judge, read, sha256, verdicts

AGENT = "urn:kk:agent:watcher-spans"
# Current claims with a quoted reference that pins a line range of a file: source. Only what this role may read.
PINNED = """select c.id::text, c.scope, r.quote, r.span->>'source', r.span->>'value'
            from api.claims c join api.claim_references r on r.claim_id = c.id
            where c.status <> 'deprecated' and c.redacted_at is null and r.quote is not null
              and r.span->>'type' = 'FragmentSelector' and r.span->>'source' like 'file:%'
            order by c.id, r.span->>'source', r.span->>'value'"""
# This method's latest verdict on each claim it has judged that is still current.
LATEST = """select distinct on (v.claim_id) v.claim_id::text, v.verdict, v.recorded_at::text
            from api.verifications v join api.claims c on c.id = v.claim_id
            where v.method = %s and c.status <> 'deprecated' and c.redacted_at is null
            order by v.claim_id, v.recorded_at desc"""


def change_sets(cur, roots: list[Path]) -> list[dict]:
    """The verification change sets one pass would submit."""
    cur.execute(PINNED)
    scope: dict[str, str] = {}
    problems: dict[str, list[dict]] = {}
    files: dict[str, str | None] = {}
    for claim, sc, quote, source, locator in cur.fetchall():
        scope[claim] = sc
        problems.setdefault(claim, [])
        if source not in files:
            files[source] = read(roots, source)
        why = judge(quote, locator, files[source])
        if why:
            problems[claim].append({"source": source, "locator": locator, "pinned_sha256": sha256(quote), **why})
    cur.execute(LATEST, (METHOD,))
    latest, since = {}, {}
    for claim, verdict, at in cur.fetchall():
        latest[claim], since[claim] = verdict, at
    ops_by_scope: dict[str, list] = {}
    for claim, verdict, details in verdicts(problems, latest):
        ops_by_scope.setdefault(scope[claim], []).append(
            {"op": "add_verification", "claim": claim, "verdict": verdict, "method": METHOD, "details": details})
    out = []
    for sc, ops in sorted(ops_by_scope.items()):
        # The time of each claim's latest verdict is part of the key: flagging a claim again after it was
        # restored is a new change set, not the first one returned again.
        digest = hashlib.sha256(json.dumps([ops, [since.get(op["claim"]) for op in ops]], sort_keys=True)
                                .encode()).hexdigest()[:32]
        out.append({"idempotency_key": f"spans:{digest}", "attributed_to": AGENT, "target_scope": sc, "ops": ops})
    return out


class Pass:
    def __init__(self, roots: list[Path]):
        self.roots = roots

    def __call__(self, conn) -> None:
        with conn.cursor() as cur:
            for cs in change_sets(cur, self.roots):
                try:
                    with run(cur, METHOD) as (run_id, outputs):
                        outputs["ops"] = len(cs["ops"])
                        status = kernel_submit(cur, cs, run_id)["status"]
                    flagged = sum(op["verdict"] == "inconclusive" for op in cs["ops"])
                    print(f"spans: {cs['target_scope']}: {flagged} flagged, {len(cs['ops']) - flagged} restored -> {status}",
                          flush=True)
                except psycopg.Error as e:  # one bad scope must not stop the others
                    print(f"spans: {cs['target_scope']}: {e.diag.message_primary or e}", flush=True)


def roots_from_env() -> list[Path]:
    raw = os.environ.get("KK_SOURCE_ROOTS") or os.environ.get("KK_SOURCE_ROOT") or os.getcwd()
    return [Path(p) for p in raw.split(os.pathsep) if p]


def main() -> None:
    roots = roots_from_env()
    if not any(r.is_dir() for r in roots):
        sys.exit(f"spans: none of the source roots exists ({', '.join(map(str, roots))}); every file would read as gone")
    with connect(os.environ.get("KK_ROLE", "kkm_watcher_spans")) as conn:
        if conn.execute("select to_regclass('api.verifications')").fetchone()[0] is None:
            sys.exit("spans: not installed (its migration adds api.verifications)")
        print(f"spans: file: sources under {', '.join(map(str, roots))}; listening on kernel_change_set", flush=True)
        listen(conn, Pass(roots), wake=lambda p: json.loads(p).get("status") == "applied")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(0)
