"""Belief worker: scores claims and submits the changed beliefs itself. Needs no runner.

It listens on kernel_change_set and runs a pass whenever a change set is applied, plus a sweep on start
and every KK_SWEEP_SECONDS (NOTIFY is not durable). A pass looks at claims recorded since the last pass
and at claims that still have no belief (everything on the first pass), widens to every claim on the
same subjects, scores them (model.score) and submits one change set of add_belief ops per scope, each
generated by its own run. Its own belief change sets add no claims, so they end the cycle.

Runs inside `kk serve`, or alone: python -m belief_corroboration (needs the kk package for kk.lib).
Env: DATABASE_URL (a login that may SET ROLE to KK_ROLE, e.g. kk_authenticator), KK_ROLE (default
kkm_belief), KK_SWEEP_SECONDS (default 30).
"""
import hashlib
import json
import os
import sys

import psycopg

from kk.lib import connect, listen, run
from kk.lib import submit as kernel_submit

from .model import AGAINST, FOR, MODEL, PREMISE_CAP, REFUTED_CAP, Claim, score

AGENT = "urn:kk:agent:belief-corroboration"
MODULE = "urn:kk:module:belief-corroboration-v0"
FUNCTIONAL_TYPE = "http://www.w3.org/2002/07/owl#FunctionalProperty"
RDF_TYPE = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type"
EVIDENCE = FOR | AGAINST
COLUMNS = ("id, subject, predicate, object_entity, object_value, statement_key, scope, attributed_to, "
           "valid_from, valid_to, status, belief")


TMS = "urn:kk:module:truth-maintenance"
# Each verifier's latest verdict on each claim (a later verdict by the same method replaces an earlier one).
VERDICTS = """select distinct on (claim_id, method) claim_id, method, verdict from api.verifications
              where claim_id = any(%s) order by claim_id, method, recorded_at desc"""
LATEST_TMS = f"""(select v.verdict from api.verifications v where v.claim_id = api.claims.id and v.method = '{TMS}'
                 order by v.recorded_at desc limit 1)"""
# Claims whose belief is out of step with their verdicts: refuted by a verifier but above that cap (D-67);
# a premise withdrawn but above that cap; premises current again but still capped (D-89).
STALE = f""" or (belief > {REFUTED_CAP} and exists (select 1 from api.verifications v
                                                  where v.claim_id = api.claims.id and v.verdict = 'refuted'))
            or (belief > {PREMISE_CAP} and {LATEST_TMS} = 'inconclusive')
            or ({LATEST_TMS} = 'supported' and (select b.explanation ? 'premise_withdrawn' from kernel.belief b
                where b.claim_id = api.claims.id order by b.computed_at desc limit 1))"""


def change_sets(cur, watermark) -> tuple[list[dict], object]:
    """The belief change sets one pass would submit, and the new watermark."""
    cur.execute("select to_regclass('api.verifications') is not null")
    verified = cur.fetchone()[0]
    cur.execute(f"""select subject, recorded_at, predicate, object_entity from api.claims
                    where %(w)s::timestamptz is null or recorded_at > %(w)s
                       or (belief is null and status <> 'deprecated'){STALE if verified else ""}""", {"w": watermark})
    new = cur.fetchall()
    if not new:
        return [], watermark
    watermark = max([r[1] for r in new] + ([watermark] if watermark else []))
    # The subjects of new claims, and the entities new evidence bears on (D-62), with the evidence
    # claims that point at them.
    subjects = sorted({r[0] for r in new} | {r[3] for r in new if r[3] and r[2] in EVIDENCE})
    cur.execute(f"""select {COLUMNS} from api.claims
                    where subject = any(%(s)s) or (object_entity = any(%(s)s) and predicate = any(%(e)s))""",
                {"s": subjects, "e": sorted(EVIDENCE)})
    cols = [d.name for d in cur.description]
    rows = [dict(zip(cols, r)) for r in cur.fetchall()]
    cur.execute("select claim_id, coalesce(artifact, source_uri) from api.claim_references where claim_id = any(%s)",
                ([r["id"] for r in rows],))
    sources: dict = {}
    for claim_id, source in cur.fetchall():
        sources.setdefault(claim_id, set()).add(source)
    refuted: dict = {}
    undermined: set = set()
    if verified:
        cur.execute(VERDICTS, ([r["id"] for r in rows],))
        for claim_id, method, verdict in cur.fetchall():
            if verdict == "refuted":
                refuted.setdefault(claim_id, set()).add(method)
            if method == TMS and verdict == "inconclusive":
                undermined.add(claim_id)
    cur.execute("select subject from api.claims where predicate = %s and object_entity = %s and status <> 'deprecated'",
                (RDF_TYPE, FUNCTIONAL_TYPE))
    functional = {r[0] for r in cur.fetchall()}
    claims = [Claim(str(r["id"]), r["statement_key"], r["subject"], r["predicate"],
                    json.dumps(r["object_entity"] or r["object_value"], sort_keys=True), r["attributed_to"],
                    frozenset(sources.get(r["id"], ())), r["valid_from"], r["valid_to"],
                    r["status"] == "deprecated", r["object_entity"], tuple(sorted(refuted.get(r["id"], ()))),
                    r["id"] in undermined) for r in rows]
    beliefs = score(claims, functional)
    ops_by_scope: dict[str, list] = {}
    for r in rows:
        if str(r["id"]) not in beliefs:
            continue
        value, explanation = beliefs[str(r["id"])]
        if r["belief"] is None or abs(r["belief"] - value) > 1e-4:
            ops_by_scope.setdefault(r["scope"], []).append(
                {"op": "add_belief", "claim": str(r["id"]), "model": MODEL, "value": value,
                 "explanation": explanation})
    out = []
    for scope, ops in sorted(ops_by_scope.items()):
        digest = hashlib.sha256(json.dumps(ops, sort_keys=True).encode()).hexdigest()[:24]
        out.append({"idempotency_key": f"belief:{digest}", "attributed_to": AGENT, "target_scope": scope,
                    "ops": ops})
    return out, watermark


def submit(cur, cs: dict) -> None:
    """Submit one change set, generated by its own run."""
    with run(cur, MODULE) as (run_id, outputs):
        outputs["ops"] = len(cs["ops"])
        status = kernel_submit(cur, cs, run_id)["status"]
    print(f"{cs['target_scope']}: {len(cs['ops'])} beliefs -> {status}", flush=True)


class Pass:
    """One belief pass per wake-up; remembers the watermark between passes."""

    def __init__(self):
        self.watermark = None

    def __call__(self, conn) -> None:
        with conn.cursor() as cur:
            sets, self.watermark = change_sets(cur, self.watermark)
            for cs in sets:
                try:
                    submit(cur, cs)
                except psycopg.Error as e:  # one bad scope must not stop the others
                    print(f"{cs['target_scope']}: {e.diag.message_primary or e}", flush=True)


def applied(payload: str) -> bool:
    return json.loads(payload).get("status") == "applied"


def main() -> None:
    with connect(os.environ.get("KK_ROLE", "kkm_belief")) as conn:
        print("belief: listening on kernel_change_set", flush=True)
        # Wake when a change set is applied, or after the sweep interval at the latest.
        listen(conn, Pass(), wake=applied)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(0)
