"""Wikidata's property constraints as a processor (D-108): reports the claims that break one, with no model.

A pass reads the constraints (claims on properties, predicate wdt:P2302) and the claims they constrain through
Substrate's read model (`substrate.usable`: the claims in force by Wikidata's rank rule, only what this role may
read), checks them (check.violations) and submits one change set of add_verification ops per scope, each
generated by its own run: inconclusive for a claim that breaks a constraint (the details name each constraint,
its kind and why), supported again when it no longer does. A report, never a block, and not a refutation: it
does not cap belief and no claim is changed or deleted. The latest verdict of this method decides, so running
again over an unchanged kernel submits nothing.

Runs inside `kk serve` (part `constraints`), or alone: python -m constraints_wikidata.
Env: DATABASE_URL (a login that may SET ROLE to KK_ROLE), KK_ROLE (default kkm_constraints_wikidata),
KK_SWEEP_SECONDS (default 30).
"""
import hashlib
import json
import os
import sys

import psycopg
from psycopg.rows import dict_row

from kk.lib import connect, listen, run
from kk.lib import submit as kernel_submit

from .check import CONSTRAINT, INSTANCE_OF, METHOD, SUBCLASS_OF, verdicts, violations

AGENT = "urn:kk:agent:constraints-wikidata"
COLUMNS = "id::text as id, subject, predicate, object_entity, object_value, qualifiers, scope"
CONSTRAINTS = f"select {COLUMNS} from substrate.usable where predicate = %s order by id"
CLAIMS = f"select {COLUMNS} from substrate.usable where predicate = any(%s) order by id"
HIERARCHY = f"select {COLUMNS} from substrate.usable where predicate = any(%s) and object_entity is not null order by id"
# This method's latest verdict on each claim it has judged that is still current, with what it said.
LATEST = """select distinct on (v.claim_id) v.claim_id::text as id, v.verdict, v.details, c.scope, v.recorded_at::text as at
            from api.verifications v join api.claims c on c.id = v.claim_id
            where v.method = %s and c.status <> 'deprecated' and c.redacted_at is null
            order by v.claim_id, v.recorded_at desc"""


def change_sets(cur, problems: list[dict] | None = None) -> list[dict]:
    """The verification change sets one pass would submit."""
    cur.execute(CONSTRAINTS, (CONSTRAINT,))
    constraints = cur.fetchall()
    props = sorted({c["subject"] for c in constraints})
    claims = []
    if props:
        cur.execute(CLAIMS, (props,))
        claims = cur.fetchall()
    cur.execute(HIERARCHY, ([INSTANCE_OF, SUBCLASS_OF],))
    found = violations(constraints, claims, cur.fetchall(), problems)
    cur.execute(LATEST, (METHOD,))
    latest, scope, since = {}, {c["id"]: c["scope"] for c in claims}, {}
    for r in cur.fetchall():
        latest[r["id"]] = (r["verdict"], (r["details"] or {}).get("violations"))
        scope.setdefault(r["id"], r["scope"])
        since[r["id"]] = r["at"]
    ops_by_scope: dict[str, list] = {}
    for claim, verdict, details in verdicts(found, latest):
        ops_by_scope.setdefault(scope[claim], []).append(
            {"op": "add_verification", "claim": claim, "verdict": verdict, "method": METHOD, "details": details})
    out = []
    for sc, ops in sorted(ops_by_scope.items()):
        # The time of each claim's latest verdict is part of the key: reporting a claim again after it was
        # cleared is a new change set, not the first one returned again.
        digest = hashlib.sha256(json.dumps([ops, [since.get(op["claim"]) for op in ops]], sort_keys=True)
                                .encode()).hexdigest()[:32]
        out.append({"idempotency_key": f"constraints:{digest}", "attributed_to": AGENT, "target_scope": sc, "ops": ops})
    return out


def one_pass(conn) -> None:
    with conn.cursor() as cur:
        problems: list[dict] = []
        with conn.cursor(row_factory=dict_row) as reader:
            sets = change_sets(reader, problems)
        for p in {(p["constraint"], p["pattern"], p["error"]) for p in problems}:
            print(f"constraints: {p[0]}: the pattern {p[1]!r} is not a regular expression ({p[2]})", flush=True)
        for cs in sets:
            try:
                with run(cur, METHOD) as (run_id, outputs):
                    outputs["ops"] = len(cs["ops"])
                    status = kernel_submit(cur, cs, run_id)["status"]
                reported = sum(op["verdict"] == "inconclusive" for op in cs["ops"])
                print(f"constraints: {cs['target_scope']}: {reported} reported, {len(cs['ops']) - reported} cleared -> {status}",
                      flush=True)
            except psycopg.Error as e:  # one bad scope must not stop the others
                print(f"constraints: {cs['target_scope']}: {e.diag.message_primary or e}", flush=True)


def main() -> None:
    with connect(os.environ.get("KK_ROLE", "kkm_constraints_wikidata")) as conn:
        if conn.execute("select to_regclass('substrate.usable')").fetchone()[0] is None:
            sys.exit("constraints: view-substrate is not installed (this reads substrate.usable)")
        print("constraints: Wikidata's property constraints over the claims; listening on kernel_change_set", flush=True)
        listen(conn, one_pass, wake=lambda p: json.loads(p).get("status") == "applied")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(0)
