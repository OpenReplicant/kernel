"""Cut a vocabulary pack from an upstream ontology: only the terms we use, with their upstream
statements (type, label, comment or definition, sub-class, domain, range, inverse), plus their
super-classes and super-properties so the hierarchy stays intact. Statements with blank-node objects
(unions, restrictions) are left out. The output is a local pack file (ontology/*.ttl) that the pack
loader installs; the header records where it came from (M2-T0, D-47).

Usage: python scripts/vocab_subset.py UPSTREAM_FILE --ns IRI --prefix P --source URL --license URL \
           --version V [--revision N] TERM... > ontology/<pack>.ttl
"""
import argparse
import hashlib
import sys
from pathlib import Path

import rdflib
from rdflib import OWL, RDF, RDFS, SKOS, BNode, Literal, URIRef

KEEP = [RDF.type, RDFS.label, RDFS.comment, SKOS.definition, RDFS.subClassOf, RDFS.subPropertyOf,
        RDFS.domain, RDFS.range, OWL.inverseOf]
KINDS = {OWL.Class, RDFS.Class, OWL.ObjectProperty, OWL.DatatypeProperty, OWL.AnnotationProperty,
         RDF.Property}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("upstream")
    ap.add_argument("--ns", required=True)
    ap.add_argument("--prefix", required=True)
    ap.add_argument("--source", required=True, help="where the upstream file was fetched from")
    ap.add_argument("--license", required=True)
    ap.add_argument("--version", required=True, help="upstream version")
    ap.add_argument("--revision", type=int, default=1,
                    help="our subset's revision; bump it when the term list changes (the pack's install key)")
    ap.add_argument("--label", required=True)
    ap.add_argument("terms", nargs="+")
    a = ap.parse_args()

    raw = Path(a.upstream).read_bytes()
    up = rdflib.Graph().parse(data=raw, format="turtle")
    want = [URIRef(a.ns + t) for t in a.terms]
    seen, todo = set(), list(want)
    while todo:                                   # close over super-classes and super-properties
        t = todo.pop()
        if t in seen:
            continue
        if (t, None, None) not in up:
            sys.exit(f"{t} is not defined upstream")
        seen.add(t)
        for p in (RDFS.subClassOf, RDFS.subPropertyOf):
            todo += [o for o in up.objects(t, p) if isinstance(o, URIRef) and str(o).startswith(a.ns)]

    g = rdflib.Graph()
    g.bind(a.prefix, a.ns)
    for pfx, ns in (("rdfs", RDFS), ("owl", OWL), ("skos", SKOS), ("dcterms", "http://purl.org/dc/terms/")):
        g.bind(pfx, ns)
    ont = URIRef(a.ns.rstrip("#/"))
    g.add((ont, RDF.type, OWL.Ontology))
    g.add((ont, RDFS.label, Literal(a.label)))
    g.add((ont, OWL.versionInfo, Literal(f"{a.version}+s{a.revision}")))
    g.add((ont, URIRef("http://purl.org/dc/terms/license"), URIRef(a.license)))
    g.add((ont, URIRef("http://purl.org/dc/terms/source"), URIRef(a.source)))
    for t in sorted(seen):
        for p in KEEP:
            for o in up.objects(t, p):
                if isinstance(o, BNode):
                    continue
                if p == RDF.type and o not in KINDS:
                    continue
                if isinstance(o, Literal) and o.language not in (None, "en"):
                    continue
                if p in (RDFS.subClassOf, RDFS.subPropertyOf, OWL.inverseOf) and o not in seen \
                        and str(o).startswith(a.ns):
                    continue
                if isinstance(o, Literal):
                    o = Literal(" ".join(str(o).split()), lang=o.language)   # one line per value
                g.add((t, p, o))
        g.add((t, RDFS.isDefinedBy, ont))
    digest = hashlib.sha256(raw).hexdigest()
    sys.stdout.write(
        f"# {a.label}: the subset of terms this platform uses (generated by scripts/vocab_subset.py;\n"
        f"# regenerate, don't edit). Upstream {a.source} version {a.version}, sha256 {digest}; subset revision {a.revision}.\n"
        f"# License {a.license}. Terms: {' '.join(a.terms)}\n\n")
    sys.stdout.write(g.serialize(format="turtle"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
