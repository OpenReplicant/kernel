"""kk distribution bundle NAME: a folder that runs a distribution with no clone and no build (D-120).

Writes compose.yaml (images by tag from GHCR, no `build:`; Postgres, the one-shot init, the kernel serving the
distribution's parts, and Caddy; ports on 127.0.0.1; named volumes), Caddyfile, .env.example (every setting;
secrets empty, with how to make each) and README.md. Nothing comes from the machine that runs the command: the
output depends on the distribution's manifest, the repository's pinned Caddy image and the image tag.
Deterministic, so a committed bundle can be checked against it (scripts/check_bundles.py).
"""
from __future__ import annotations

import re
from pathlib import Path

from .distributions import ROOT, load, names

REGISTRY = "ghcr.io/openreplicant"
KERNEL_IMAGE = f"{REGISTRY}/kernel"
DB_IMAGE = f"{REGISTRY}/kernel-postgres"
DEFAULT_TAG = "main"


def caddy_image() -> str:
    """The Caddy image the repository's deploy/.env.example pins."""
    m = re.search(r"^CADDY_IMAGE=(\S+)", (ROOT / "deploy/.env.example").read_text(), re.M)
    assert m, "deploy/.env.example pins no CADDY_IMAGE"
    return m.group(1)


def ports(name: str) -> tuple[int, int]:
    """The ports `kk up --distribution` chooses, so stacks run side by side (kk/up.py distribution_settings)."""
    i = names().index(name) + 1
    return 8080 + i, 5432 + i


CADDYFILE = """\
# Front door, local only (the compose file publishes 127.0.0.1). Replaceable by any reverse proxy: the kernel
# depends on nothing here. To serve a public host name over HTTPS, see deploy/public.yaml in the repository.
:80 {
	encode zstd gzip
	reverse_proxy kernel:8000
}
"""


def compose(name: str, tag: str) -> str:
    d = load(name)
    http, db = ports(name)
    parts = ",".join(d["settings"]["serve"])
    return f"""\
# {d['title']}: {d['does']}
# Generated by `kk distribution bundle {name}`; edit .env, not this file. Images are pulled, never built here.
#   cp .env.example .env     # fill it in (README.md says how)
#   podman compose up -d     # docker compose works too
name: kk-{name}

x-kk: &kk
  image: ${{KK_IMAGE:-{KERNEL_IMAGE}:{tag}}}
  read_only: true
  cap_drop: [ALL]
  security_opt: [no-new-privileges:true]
  tmpfs: [/tmp]

services:

  # The kernel's store: Postgres with pgvector, pg_cron, pgmq and pgGraph.
  db:
    image: ${{KK_DB_IMAGE:-{DB_IMAGE}:{tag}}}
    command: ["postgres", "-c", "shared_preload_libraries=pg_cron,graph", "-c", "cron.database_name=kk"]
    environment:
      POSTGRES_DB: kk
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD:?set in .env}}
    volumes:
      - db-data:/var/lib/postgresql/data
    ports:
      - "127.0.0.1:${{KK_DB_PORT:-{db}}}:5432"
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres -d kk"]
      interval: 5s
      retries: 20
    restart: unless-stopped

  # One-shot: installs the kernel, the default modules and the packs (does nothing once installed). Also the
  # place to run admin commands: `podman compose run --rm init kk ...` (README.md).
  init:
    <<: *kk
    command: ["kk", "init"]
    environment:
      KK_ADMIN_URL: postgresql://postgres:${{POSTGRES_PASSWORD}}@db:5432/kk
      KK_AUTHENTICATOR_PASSWORD: ${{KK_AUTHENTICATOR_PASSWORD:?set in .env}}
      KK_JWT_SECRET: ${{KK_JWT_SECRET:?set in .env}}
      KK_DISTRIBUTION: {name}
      KK_ARTIFACTS: /artifacts
      KK_CHATS: /chats
      HOME: /tmp
      KK_HOME: /tmp/kk-home
    volumes:
      - kk-artifacts:/artifacts
      - kk-chats:/chats
    depends_on:
      db: {{condition: service_healthy}}
    restart: "no"

  # MCP over HTTP, the UI, the validator, the belief model and the rest of {name}'s parts.
  kernel:
    <<: *kk
    command: ["kk", "serve", "--host", "0.0.0.0", "--only", "${{KK_SERVE_PARTS:-{parts}}}"]
    environment:
      DATABASE_URL: postgresql://kk_authenticator:${{KK_AUTHENTICATOR_PASSWORD}}@db:5432/kk
      KK_JWT_SECRET: ${{KK_JWT_SECRET:?set in .env}}
      KK_ARTIFACTS: /store
      KK_DISTRIBUTION: {name}
      KK_CHATS: /chats
    volumes:
      - kk-artifacts:/store:ro
      - kk-chats:/chats
    depends_on:
      init: {{condition: service_completed_successfully}}
    restart: unless-stopped

  caddy:
    image: ${{CADDY_IMAGE:-{caddy_image()}}}
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro,z
    ports:
      - "127.0.0.1:${{KK_HTTP_PORT:-{http}}}:80"
    depends_on: [kernel]
    restart: unless-stopped

volumes:
  db-data:
  kk-artifacts:
  kk-chats:
"""


def env_example(name: str, tag: str) -> str:
    http, db = ports(name)
    return f"""\
# Copy to .env (never commit it) and fill in the three secrets. Each is a random string; make them with
#   openssl rand -hex 24      (the two passwords)
#   openssl rand -hex 32      (the JWT secret; the kernel needs at least 32 characters)

POSTGRES_PASSWORD=
# The services' login (switches to each part's own role). Never give it to an agent.
KK_AUTHENTICATOR_PASSWORD=
# HS256 secret for MCP over HTTP: the kernel verifies tokens, `kk token ROLE` mints them.
KK_JWT_SECRET=

# Ports, published on 127.0.0.1 only. Change them to run several bundles side by side.
KK_HTTP_PORT={http}
KK_DB_PORT={db}

# The images. Pin a release tag (v1.2.3) or a digest once you run this for real; `{tag}` follows the main branch.
KK_IMAGE={KERNEL_IMAGE}:{tag}
KK_DB_IMAGE={DB_IMAGE}:{tag}
CADDY_IMAGE={caddy_image()}

# Leave empty to run the parts {name} chooses (see compose.yaml).
KK_SERVE_PARTS=
"""


def readme(name: str, tag: str) -> str:
    d = load(name)
    http, _ = ports(name)
    run = "podman compose run --rm"
    demo = d["demo"]
    if demo in ("interview", "order-to-cash"):
        load_step = f"""\
## Load the demo

```sh
{run} init kk demo --distribution {name} --no-stack
```

It installs this distribution's modules, loads the demo data ({'a scripted interview that fills the organisation and process maps' if demo == 'interview' else 'an order-to-cash event log, its BPMN model and a written procedure'}) and prints the owner's sign-in
(`owner_sign_in`). Running it again changes nothing. It sets the owner's password afresh, so use the one it prints.
"""
        signin = f"""\
Open http://127.0.0.1:{http}/ui/ and sign in as `owner` with the password the demo printed.
To sign in without loading the demo, make the owner first (the password is printed once):

```sh
{run} init kk person add owner --steward
{run} init sh -c 'mkdir -p /tmp/p && kk up --distribution {name} --no-stack --no-scan /tmp/p'
```

The second command installs this distribution's modules; the demo does it for you.
"""
    else:
        load_step = f"""\
## Load data

{name} has no scripted demo{' (its demo is the devops overlay in the repository, `scripts/e2e_devops.sh`, which needs the source tree)' if demo == 'devops' else ''}. Read your own data with the distribution's modules (docs/modules.md in the repository).
"""
        signin = f"""\
Make the owner and install this distribution's modules (the password is printed once as `owner_sign_in`):

```sh
{run} init sh -c 'mkdir -p /tmp/p && kk up --distribution {name} --no-stack --no-scan /tmp/p'
```

Open http://127.0.0.1:{http}/ui/ and sign in as `owner` with that password.
"""
    extra = ""
    if name == "devops":
        extra = ("\n`devops` observes a running service. This bundle has the kernel's side only (the database, the kernel and the "
                 "UI); the metrics observer and the actuator run as their own sandboxed containers installed with "
                 "`kk module install` from the repository (docs/demo.md, the devops demo).\n")
    return f"""\
# {d['title']}

{d['does']}

This folder runs the `{name}` distribution of the [Knowledge Kernel](https://github.com/OpenReplicant/kernel) from
published images. There is nothing to clone or build.

## Start

```sh
cp .env.example .env              # 1. copy the settings
$EDITOR .env                      # 2. fill in the three secrets (how is written in the file)
podman compose up -d              # 3. start it (docker compose works the same)
```

Images are `{KERNEL_IMAGE}` and `{DB_IMAGE}`, tag `{tag}` (set `KK_IMAGE` and `KK_DB_IMAGE` in `.env` to pin a
release). The packages are public, so pulling needs no registry login. The first start takes a minute while the
database initialises. Check with `podman compose ps`.

## Sign in

{signin}
{load_step}{extra}
## Connect an agent

```sh
{run} init kk agent add claude-code      # prints the agent's password once
```

The agent's MCP server is `http://127.0.0.1:{http}/mcp` with a bearer token (`{run} init kk token agent_claude_code`);
the repository's docs/harness.md covers the harness side.

## Stop, reset

```sh
podman compose down        # stops; the data stays in the volumes
podman compose down -v     # stops and deletes the data
```

Ports are on 127.0.0.1 only. Generated by `kk distribution bundle {name}`; do not put anything of yours in this
folder except `.env`, which stays out of version control.
"""


def write(name: str, out: Path, tag: str = DEFAULT_TAG) -> list[str]:
    """Write the bundle into out; the files whose content changed."""
    load(name)
    files = {"compose.yaml": compose(name, tag), "Caddyfile": CADDYFILE, ".env.example": env_example(name, tag),
             "README.md": readme(name, tag)}
    out.mkdir(parents=True, exist_ok=True)
    changed = []
    for f, text in files.items():
        p = out / f
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
            changed.append(f)
    return changed
